def build_hub_doc(title: str, intro: str, rows_data: list):
    tbl = [[_c("回测主题", True), _c("时间与样本", True), _c("核心实证结论", True), _c("实战用法", True)]]
    for r in rows_data:
        tbl.append([_c(r[0], True), _c(r[1]), _c(r[2]), _c(r[3])])
    return {
        "title": title,
        "blocks": [
            P([R(intro, background_color=3), R("本目录集中归档全量专项小回测，严禁混放有效与证伪结论。")]),
            P([R("一、目录使用说明", bold=True)]),
            B([R("左侧子目录可直接点开每篇完整实证报告与细项表格。")]),
            B([R("下方索引表浓缩了全部回测的样本周期、结论与实战边界。")]),
            B([R("所有新增小回测均严守时点口径、次日成交与真实扣费检验。")]),
            BL(), BL(), BL(),
        ],
        "tables": [(f"{title}全量索引表（共 {len(rows_data)} 项）", tbl)],
        "img_path": None,
    }
