OPP_COST_MAX_SWITCH = 0.10   # 单次机会成本换仓上限(占净值), 回测定版前的保守约束


def opportunity_cost_flag(excess_5d, excess_20d, excess_60d, rank_pct_5d,
                          has_catalyst_30d=False, has_better_alternative=False):
    """机会成本门判定。返回 (是否触发, 理由)。⛔只建议不自动执行(见上方证据等级)。
    excess_*: 相对沪深300的超额收益% | rank_pct_5d: 5日超额在全持仓中的分位(0=最弱,1=最强)"""
    negs = sum(1 for x in (excess_5d, excess_20d, excess_60d) if x is not None and x < 0)
    if negs < 2:
        return False, None
    if rank_pct_5d is not None and rank_pct_5d > 0.33:
        return False, None
    if has_catalyst_30d:
        return False, '三窗口弱势但30日内有硬催化未兑现→等催化,不因横盘卖(催化窗口内横盘是常态)'
    if not has_better_alternative:
        return False, '三窗口弱势但无已研究的替代标的→卖了拿现金比拿弱票更差,不触发'
    return True, (f'机会成本触发: 三窗口超额{excess_5d:+.1f}/{excess_20d:+.1f}/{excess_60d:+.1f}, '
                  f'{negs}个为负且5日超额处全持仓最弱1/3, 且存在已研究的更优替代 '
                  f'→ 建议换仓(单次≤{OPP_COST_MAX_SWITCH*100:.0f}%净值)。'
                  f'⛔非thesis证伪, 非名单变化(T14边界), 是资金效率判定')


