# 【机制】不靠自觉。任何建仓前, 若该标的存在**已写下的计划仓位**, 实际下单不得超过计划。
#   要超必须显式给出新证据(不是"它涨了"), 并留痕。
# ══════════════════════════════════════════════════════════════════════════════
PLAN_TOLERANCE = 0.01   # 允许的执行偏差(1pp), 覆盖股数取整造成的零头


def plan_consistency_check(ticker, intended_pct, plan_pct, override_evidence=None):
    """计划一致性闸门。返回 (是否放行, 理由)。
    plan_pct=None 表示该标的不在任何已写计划里(全新决策, 放行但留痕)。
    override_evidence: 要超计划必须给的新证据。⛔"它涨了""板块很强""怕踏空"都不算证据——
      那些恰恰是冲动追涨的自我叙述。合格的证据只有: 基本面出现计划时未知的新事实
      (订单/产能/政策/催化剂日期确认), 且必须可查证。"""
    if plan_pct is None:
        return True, f'⚠️{ticker}不在已写计划内(全新决策,{intended_pct*100:.1f}%),已留痕'
    if intended_pct <= plan_pct + PLAN_TOLERANCE:
        return True, None
    excess = (intended_pct - plan_pct) * 100
    if not override_evidence:
        return False, (f'⛔计划一致性闸门: {ticker}计划仓位{plan_pct*100:.0f}%, 意图{intended_pct*100:.1f}%, '
                       f'超出{excess:.1f}pp。⛔"它涨了/板块强/怕踏空"不构成超计划理由——'
                       f'那正是2026-08-10 CXO事故的原话。要超必须给计划时未知的新基本面事实且可查证。'
                       f'否则按计划{plan_pct*100:.0f}%执行')
    return True, f'⚠️超计划{excess:.1f}pp, 已给证据: {override_evidence}(留痕待复核)'


