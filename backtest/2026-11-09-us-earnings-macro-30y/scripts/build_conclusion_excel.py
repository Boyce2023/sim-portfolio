def clean_txt(s):
    if s is None:
        return ""
    s = str(s)
    s = s.replace("——", "，").replace("—", "，").replace("–", "至").replace("→", "至").replace("->", "至")
    s = s.replace("-", " ")
    s = s.replace("！", "").replace("!", "")
    return s


def init_sheet(wb, title, col_widths):
    ws = wb.create_sheet(title=title)
    ws.column_dimensions["A"].width = 1.83
    for idx, w in enumerate(col_widths, start=2):
        ws.column_dimensions[get_column_letter(idx)].width = w
    return ws


def write_table(ws, start_row, sec_title, headers, rows, num_fmts=None, bold_last_row=False):
    r = start_row
    if sec_title:
        c = ws.cell(r, 2, clean_txt(sec_title))
        c.font = FONT_SEC
        c.alignment = AL_LEFT
        r += 1
    for j, h in enumerate(headers, start=2):
        cell = ws.cell(r, j, clean_txt(h))
        cell.font = FONT_HDR
        cell.border = BDR_HDR
        cell.alignment = AL_LEFT if j == 2 else AL_RIGHT
    r += 1
    n_rows = len(rows)
    for i, row_vals in enumerate(rows):
        is_last = (i == n_rows - 1)
        for j, val in enumerate(row_vals, start=2):
            if isinstance(val, str) and val.startswith("="):
                val = val.replace("{ROW}", str(r))
            elif isinstance(val, str):
                val = clean_txt(val)
            cell = ws.cell(r, j, val)
            cell.font = FONT_BOLD if (bold_last_row and is_last) else FONT_DATA
            if num_fmts and (j - 2) in num_fmts and val is not None:
                cell.number_format = num_fmts[j - 2]
            is_text_col = isinstance(val, str) and not val.startswith("=")
            cell.alignment = AL_LEFT if (j == 2 or is_text_col) else AL_RIGHT
            if bold_last_row and is_last:
                cell.border = BDR_TOTAL
            elif is_last:
                cell.border = BDR_LAST
        r += 1
    return r + 1


